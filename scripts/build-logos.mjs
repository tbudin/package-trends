// Bakes the brand marks the package picker shows into site/logos.js.
//
// simple-icons is CC0, so the marks are the official ones and nothing has to
// be attributed or drawn from memory. Doing it here rather than at runtime
// keeps the site free of a CDN and ships only the twelve icons it uses.
//
// Each mark comes out as a standalone SVG document, because the select draws
// it as a background layer rather than as markup — see selectMarkCss in
// package-site. A background layer cannot take currentColor, so a mark that is
// nearly black or nearly white is baked once per theme in the page's own ink.
import { writeFile } from "node:fs/promises";
import * as si from "simple-icons";

const SLUGS = {
  react: "react", vue: "vuedotjs", svelte: "svelte", preact: "preact",
  "solid-js": "solid", next: "nextdotjs", typescript: "typescript",
  vite: "vite", express: "express", lodash: "lodash", zod: "zod",
  // Whatever the reader types in: the registry's own mark, not a framework's.
  other: "npm",
};

// --fg in site.config.js, light and dark.
const INK = { light: "#1a1a17", dark: "#eceae4" };

const luminance = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const svg = (path, fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="${fill}"><path d="${path}"/></svg>`;

const icons = {};
for (const [pkg, slug] of Object.entries(SLUGS)) {
  const icon = si[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
  if (!icon) throw new Error(`simple-icons has no mark for ${slug}`);
  const l = luminance(icon.hex);
  const vanishes = l < 0.06 || l > 0.9;
  // Only a mark that actually changes carries a second copy: the other ten
  // keep their brand colour in both themes, and pages.js ships to the browser.
  icons[pkg] = { light: svg(icon.path, vanishes ? INK.light : `#${icon.hex}`) };
  if (vanishes) icons[pkg].dark = svg(icon.path, INK.dark);
}

const body = `/* Generated by scripts/build-logos.mjs from simple-icons (CC0-1.0).
   Do not edit: run \`pnpm build:logos\` instead.

   One standalone SVG per theme. package-site turns these into the background
   layer the package select draws for whichever option is checked. */

export const logos = ${JSON.stringify(icons, null, 2)};

export const PACKAGES = Object.keys(logos).filter((k) => k !== 'other');
`;

await writeFile(new URL("../site/logos.js", import.meta.url), body);
const twice = Object.values(icons).filter((i) => i.dark).length;
console.log(`  site/logos.js — ${Object.keys(icons).length} marks (${twice} baked per theme), ${(body.length / 1024).toFixed(1)} kB`);
