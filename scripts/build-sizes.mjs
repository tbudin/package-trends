// Measures what each entry point actually costs, into site/sizes.js.
//
// The site used to state these by hand, which is a promise the build never
// checked: the figures were three entries old before anyone noticed. Here they
// are bundled exactly as a consumer's bundler would — minified, ESM, peers
// left external — and gzipped, because that is what crosses the wire.
import { gzipSync } from "node:zlib";
import { readFile, writeFile } from "node:fs/promises";
import * as esbuild from "esbuild";

const root = new URL("..", import.meta.url).pathname;
const pkg = JSON.parse(await readFile(`${root}package.json`, "utf8"));

const peers = Object.keys(pkg.peerDependencies ?? {});
const deps = Object.keys(pkg.dependencies ?? {});

// Every public subpath, mapped back to the source it is built from.
const SOURCE = {
  ".": "index.ts",
  "./react": "react.tsx",
  "./compare": "compare-react.tsx",
  "./heatmap": "heatmap-react.tsx",
};

const kB = (bytes) => `${(bytes / 1000).toFixed(1)} kB`;

const sizes = {};
for (const subpath of Object.keys(pkg.exports)) {
  const file = SOURCE[subpath];
  if (!file) continue; // ./package.json and anything else public but not code
  const out = await esbuild.build({
    bundle: true,
    format: "esm",
    target: ["es2022"],
    minify: true,
    write: false,
    external: [...peers, ...deps],
    define: { "process.env.NODE_ENV": '"production"' },
    entryPoints: [`${root}src/${file}`],
  });
  sizes[subpath] = kB(gzipSync(out.outputFiles[0].contents).length);
}

const missing = Object.keys(pkg.exports).filter((s) => s !== "./package.json" && !SOURCE[s]);
if (missing.length) throw new Error(`package.json exports ${missing.join(", ")} but scripts/build-sizes.mjs has no source for it`);

const body = `/* Generated by scripts/build-sizes.mjs. Do not edit.

   Minified, ESM, peer dependencies external, gzipped — what a consumer's
   bundler ships. Measured on every build, so the site cannot claim a size the
   package no longer has. */

export const sizes = ${JSON.stringify(sizes, null, 2)};

export const dependencies = ${JSON.stringify(deps)};
export const peerDependencies = ${JSON.stringify(peers)};
`;

await writeFile(`${root}site/sizes.js`, body);
console.log(`  site/sizes.js — ${Object.entries(sizes).map(([k, v]) => `${k} ${v}`).join(", ")}`);
